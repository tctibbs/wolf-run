def mirror(rows: list[str]) -> list[str]:
    """Flip a sprite to face the other way."""
    return [row[::-1] for row in rows]


def _patch(rows: list[str], changes: dict[int, str]) -> list[str]:
    out = list(rows)
    for index, row in changes.items():
        out[index] = row
    return out


