def validate() -> None:
    """Every grid must be rectangular and use only the three grid characters."""
    for name, grid in {**SPRITES, **{f"font {k}": v for k, v in FONT.items()}}.items():
        widths = {len(row) for row in grid}
        if len(widths) != 1:
            raise ValueError(f"{name} has ragged rows: {sorted(widths)}")
        stray = {ch for row in grid for ch in row} - set("#.o")
        if stray:
            raise ValueError(f"{name} uses unexpected characters: {sorted(stray)}")
    for name in ("wolfA", "wolfB", "wolfJump", "wolfOpen", "wolfChomp", "wolfFat"):
        if (len(SPRITES[name][0]), len(SPRITES[name])) != (32, 22):
            raise ValueError(f"{name} is not 32x22")
